CREATE TABLE IF NOT EXISTS `projects` (
    `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `slug` VARCHAR(100) NOT NULL UNIQUE,
    `code_id` VARCHAR(50) NOT NULL,
    `category` VARCHAR(50) NOT NULL,
    `filter_tag` VARCHAR(50) NOT NULL,
    `title` VARCHAR(150) NOT NULL,
    `tagline` VARCHAR(255) NOT NULL,
    `environment` VARCHAR(150) NULL,
    `performance_metric` VARCHAR(150) NULL,
    `operational_status` VARCHAR(100) DEFAULT 'Operational',
    `description` TEXT NOT NULL,
    `features_json` TEXT NULL,
    `code_filename` VARCHAR(100) NULL,
    `code_snippet` TEXT NULL,
    `technologies_json` TEXT NOT NULL,
    `github_url` VARCHAR(255) NULL,
    `demo_url` VARCHAR(255) NULL,
    `featured_image` VARCHAR(255) NULL,
    `display_order` INT NOT NULL DEFAULT 0,
    `is_featured` TINYINT(1) NOT NULL DEFAULT 0,
    `is_published` TINYINT(1) NOT NULL DEFAULT 1,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX `idx_slug` (`slug`),
    INDEX `idx_filter_tag` (`filter_tag`),
    INDEX `idx_is_published` (`is_published`),
    INDEX `idx_display_order` (`display_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
